enum ActionType {
  fiveO,    // "5-0" Karte ermöglicht es, Strafen anderer Aktionskarten zu vermeiden.
  inYoFace, // "In Yo Face" Karte zwingt den nächsten Spieler, 5 Karten zu ziehen.
  deuces,   // "Deuces" Karte zwingt den nächsten Spieler, 2 Karten zu ziehen.
  snitch,   // "Snitch" Karte erlaubt es, Handkarten mit einem anderen Spieler zu tauschen.
  deal,     // "Deal" Karte ermöglicht es, alle Handkarten mit einem anderen Spieler zu tauschen.
  busted,   // "Busted" Karte zwingt den nächsten Spieler auszusetzen.
  payback,  // "Payback" Karte ermöglicht einen Richtungswechsel und kann Strafen umkehren.
  pimpSlap, // "Pimp Slap" Karte zwingt alle anderen Spieler, Karten zu ziehen.
}
